    if [ -f "$FILE" ]; then
        echo "Processing $FILE..."
        for FA in "${!MAPPING[@]}"; do
            LUCIDE="${MAPPING[$FA]}"
            # Replace fa-solid fa-icon, fa-regular fa-icon, fa-brands fa-icon with data-lucide="mapped-icon"
            # We match class="... fa-icon ..." and replace the whole <i> tag or just the class.
            # But the requirement is to use data-lucide.
            # Let's try to find <i> tags with fa- classes and replace them.
            
            # This sed command is a bit complex because it needs to handle different FA class prefixes
            sed -i "s/class=\"fa-solid fa-$FA\([^\"]*\)\"/data-lucide=\"$LUCIDE\" class=\"\1\"/g" "$FILE"
            sed -i "s/class=\"fa-regular fa-$FA\([^\"]*\)\"/data-lucide=\"$LUCIDE\" class=\"\1\"/g" "$FILE"
            sed -i "s/class=\"fa-brands fa-$FA\([^\"]*\)\"/data-lucide=\"$LUCIDE\" class=\"\1\"/g" "$FILE"
            sed -i "s/class=\"fas fa-$FA\([^\"]*\)\"/data-lucide=\"$LUCIDE\" class=\"\1\"/g" "$FILE"
            sed -i "s/class=\"far fa-$FA\([^\"]*\)\"/data-lucide=\"$LUCIDE\" class=\"\1\"/g" "$FILE"
            sed -i "s/class=\"fab fa-$FA\([^\"]*\)\"/data-lucide=\"$LUCIDE\" class=\"\1\"/g" "$FILE"
        done
        
        # Cleanup empty classes
        sed -i 's/ class=""/ /g' "$FILE"
        sed -i 's/ class=" "/ /g' "$FILE"
    fi
done

